import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const html=readFileSync(new URL('../index.html',import.meta.url),'utf8');
const context={window:{},URL,PASS_TIME_MS:604800000};vm.createContext(context);
vm.runInContext(html.slice(html.indexOf('window.app = {'),html.indexOf('    const app = window.app;'))+'\nvar app=window.app;',context);
const app=context.app;app.userData={mcUsername:'reader'};
const s={id:'test',title:'Suggestion title',body:'Long original description https://example.com/details',createdAt:Date.now()-9*86400000,status:'passed',reviewStatus:'finalized',moderatorVerdict:'ACCEPT',moderatorFinalizedAt:Date.now(),moderatorVoteTally:{accept:4,deny:1},publishedModeratorNotes:[{body:'Public note https://example.com/notes',authorDiscord:'Moderator',createdAt:Date.now()}],comments:[{body:'Comment link https://example.com/comments',authorMc:'Reader',createdAt:Date.now()}]};
const compact=app.renderBox(s,'home');
assert.ok(compact.includes('Final moderator verdict: ACCEPT'));
assert.ok(compact.includes('class="aa-go"'));
assert.ok(compact.includes('>GO</button>'));
assert.ok(compact.includes('<fieldset'));
assert.ok(compact.includes('<legend>Suggestion title</legend>'));
assert.ok(compact.includes('aria-label="Open thread: Suggestion title"'));
assert.ok(!compact.includes('Long original description'));
assert.ok(!compact.includes('Public note'));
assert.ok(!compact.includes('Moderator votes:'));
assert.ok(!compact.includes('data-read-kind'),'Collapsed summary must not mark the original content read');
const full=app.renderBox(s,'thread');
assert.ok(full.includes('Long original description'));
assert.ok(full.includes('Final moderator verdict: ACCEPT'));
assert.ok(full.includes('Moderator votes: 4 Accept'));
assert.ok(full.includes('Published moderator notes'));
assert.ok(full.includes('Public note'));
assert.ok(full.includes('href="https://example.com/comments"'));
assert.ok(full.includes('href="https://example.com/notes"'));
assert.ok(full.includes('Comments are closed'));
assert.ok(app.renderBox({...s,status:'failed',communityVerdict:'COMMUNITY DENIED'},'home').includes('Final outcome: COMMUNITY DENIED'));
const link=app.linkify('Read (https://example.com/a_(b)). Also www.example.com/test! <script>alert(1)</script> javascript:alert(1)');
assert.ok(link.includes('href="https://example.com/a_(b)"'));
assert.ok(link.includes('</a>).'));
assert.ok(link.includes('href="https://www.example.com/test"'));
assert.ok(link.includes('&lt;script&gt;'));
assert.ok(!link.includes('href="javascript:'));
assert.ok(link.includes('rel="noopener noreferrer"'));
assert.ok(!html.includes('>Menu</div>'));
assert.ok(!html.includes('↳'));
assert.ok(html.includes('.sidebar-item::after'));
console.log('Home refinements passed: compact verdicts, full public thread, safe clickable URLs, collapsed read state, and sidebar arrows.');
