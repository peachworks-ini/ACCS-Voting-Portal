import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import vm from 'node:vm';

const html = readFileSync(new URL('../index.html', import.meta.url), 'utf8');
const moduleSource = html.match(/<script type="module">([\s\S]*?)<\/script>/)[1];
new vm.Script(moduleSource.replace(/import\s*\{[\s\S]*?\}\s*from\s*"[^"]+";/g, ''));
const context = { window: {}, console, PASS_TIME_MS: 604800000 };
vm.createContext(context);
vm.runInContext(html.slice(html.indexOf('window.app = {'), html.indexOf('    const app = window.app;')) + '\nvar app = window.app;', context);
const app = context.app;
app.userData = { mcUsername: 'Tester' };
app.msg = () => {};
assert.equal(JSON.stringify(app.parseTags(' Fun, Building,FUN, , ')), '["Building","Fun"]');
assert.equal(app.parseTags('x'.repeat(25)), null);
assert.equal(app.parseTags('gameplay'), null);
assert.equal(app.parseTags(app.tagOptions).length, 6);
assert.equal(JSON.stringify(app.tagsFor({})), '[]');
const suggestion = { id: 'one', title: 'Test', body: 'Body', createdAt: 100, status: 'active', authorAccountKey: 'other', comments: [] };
assert.equal(app.unreadActivity(suggestion).label, 'New suggestion');
app.readState.one = 100;
assert.equal(app.unreadActivity(suggestion), null);
suggestion.comments = [{ accountKey: 'other', createdAt: 150 }, { accountKey: 'tester', createdAt: 200 }, { accountKey: 'other', createdAt: 300 }];
assert.equal(app.unreadActivity(suggestion).label, '1 new reply in your thread');
app.readState.one = 300;
assert.equal(app.unreadActivity(suggestion), null);
suggestion.comments.push({ accountKey: 'tester', createdAt: 400 });
assert.equal(app.unreadActivity(suggestion), null);
suggestion.comments.push({ accountKey: 'other', createdAt: 500 });
suggestion.status = 'failed';
assert.equal(app.unreadActivity(suggestion).at, 500);
app.readState.one = 500;
assert.equal(app.unreadActivity(suggestion), null);
suggestion.authorAccountKey = 'tester';
suggestion.comments = [{ accountKey: 'other', createdAt: 600 }];
assert.equal(app.unreadActivity(suggestion).at, 600);
suggestion.status = 'vetoed';
assert.equal(app.unreadActivity(suggestion), null);
suggestion.status = 'failed';
assert.ok(app.renderBox(suggestion, 'thread').includes('Comments are closed'));
assert.ok(!app.renderBox(suggestion, 'thread').includes('comment-input-one'));
suggestion.status = 'active';
suggestion.tags = ['<script>'];
assert.ok(app.renderBox(suggestion, 'thread').includes('&lt;script&gt;'));
assert.ok(app.renderBox(suggestion, 'thread').includes('comment-input-one'));
console.log('Tag and notification checks passed.');
